// Builds .agents/skills/SKILLS_INDEX.md from the headers of the finished skills, and searches it.
// No package; Node 22.18 or later. Run from the root of the project:
//   node .agents/skills/skill-index/scripts/skill-index.ts build    # writes SKILLS_INDEX.md
//   node .agents/skills/skill-index/scripts/skill-index.ts check    # exits 1 when the file is stale
//   node .agents/skills/skill-index/scripts/skill-index.ts search <word> [<word>...]
// skill_index.py does the same with Python; both write the same bytes.
import {
  existsSync,
  readdirSync,
  readFileSync,
  realpathSync,
  writeFileSync,
} from 'node:fs';
import {
  dirname,
  join,
  resolve,
} from 'node:path';
import { fileURLToPath } from 'node:url';

export interface Entry {
  name: string;
  load: string;
  tags: string;
  description: string;
}

const MAX_RESULTS = 5;
const HERE = dirname(fileURLToPath(import.meta.url));
const DEFAULT_SKILLS = resolve(HERE, '..', '..');

// The order of Python's sorted() on strings: by code point, so both scripts write the same index.
function byCodePoint(left: string, right: string): number {
  return Number(left > right) - Number(left < right);
}

function unquote(value: string): string {
  const trimmed = value.trim();

  return /^(["']).*\1$/.test(trimmed) ? trimmed.slice(1, -1) : trimmed;
}

// The header fields of a SKILL.md: "name", "description", "metadata.id"...
function fields(text: string): Map<string, string> {
  const lines = text
    .replaceAll('\r\n', '\n')
    .split('\n');
  const result = new Map<string, string>();
  const end = lines[0] === '---' ? lines.indexOf('---', 1) : -1;
  let parent = '';

  for (const line of lines.slice(1, Math.max(end, 1))) {
    const match = /^(\s*)([A-Za-z_][\w-]*):(?:\s+(.*))?$/.exec(line);

    if (match === null) {
      continue;
    }
    const nested = (match[1] ?? '') !== '';
    const value = match[3] ?? '';

    result.set(nested ? `${parent}.${match[2] ?? ''}` : match[2] ?? '', unquote(value));
    if (!nested) {
      parent = value.trim() === '' ? match[2] ?? '' : '';
    }
  }
  return result;
}

export function entries(skills: string): Entry[] {
  return readdirSync(skills, { withFileTypes: true })
    .filter((item) => item.isDirectory() && !item.name.startsWith('_'))
    .map((item) => join(skills, item.name, 'SKILL.md'))
    .filter((path) => existsSync(path))
    .map((path) => {
      const header = fields(readFileSync(path, 'utf8'));
      const id = header.get('metadata.id') ?? '';

      return {
        name: header.get('name') ?? '',
        load: header.get('metadata.load') ?? '',
        tags: [
          id.split('-')[0] ?? '',
          header.get('metadata.nature') ?? '',
        ]
          .filter((tag) => tag !== '')
          .join(', '),
        description: header.get('description') ?? '',
      };
    })
    .sort((left, right) => byCodePoint(left.name, right.name));
}

function cell(text: string): string {
  return text.replaceAll('|', '\\|');
}

export function render(list: readonly Entry[]): string {
  return [
    '# Skills index',
    '',
    'Generated by `node .agents/skills/skill-index/scripts/skill-index.ts build`. Do not edit by hand.',
    `${list.length} skills. Load at most 3 for one task with the \`skill\` tool.`,
    '',
    '| Skill | Load | Tags | Description |',
    '| --- | --- | --- | --- |',
    ...list.map((entry) => `| \`${entry.name}\` | ${entry.load} | ${cell(entry.tags)} | ${cell(entry.description)} |`),
    '',
  ].join('\n');
}

function words(text: string): string[] {
  return text
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter((word) => word.length > 1);
}

// The skills whose name, tags or description hold the most query words; the name counts three times.
export function search(list: readonly Entry[], query: readonly string[]): Entry[] {
  const wanted = query.flatMap((item) => words(item));

  return list
    .map((entry) => {
      const name = words(entry.name);
      const rest = words(`${entry.tags} ${entry.description}`);
      const score = wanted.reduce((sum, word) => sum + (name.includes(word) ? 3 : 0) + (rest.includes(word) ? 1 : 0), 0);

      return {
        entry,
        score,
      };
    })
    .filter((item) => item.score > 0)
    .sort((left, right) => right.score - left.score || byCodePoint(left.entry.name, right.entry.name))
    .slice(0, MAX_RESULTS)
    .map((item) => item.entry);
}

function main(): void {
  const [
    command,
    ...rest
  ] = process.argv.slice(2);
  const skills = process.env['SKILLS_DIR'] ?? DEFAULT_SKILLS;
  const path = join(skills, 'SKILLS_INDEX.md');
  const text = render(entries(skills));

  if (command === 'build') {
    writeFileSync(path, text);
    console.log(`Wrote ${path}.`);
  } else if (command === 'check') {
    const fresh = existsSync(path) && readFileSync(path, 'utf8') === text;

    console.log(fresh ? 'SKILLS_INDEX.md is up to date.' : 'SKILLS_INDEX.md is stale: run the build command.');
    process.exitCode = fresh ? 0 : 1;
  } else if (command === 'search' && rest.length > 0) {
    const found = search(entries(skills), rest);

    for (const entry of found) {
      console.log(`${entry.name} (${entry.load}): ${entry.description}`);
    }
    console.log(`${found.length} results.`);
  } else {
    console.log('Usage: node skill-index.ts build | check | search <word> [<word>...]');
    process.exitCode = 2;
  }
}

// Run main only when this file is the command, whatever symbolic links lead to it.
if (realpathSync(process.argv[1] ?? '.') === realpathSync(fileURLToPath(import.meta.url))) {
  main();
}
