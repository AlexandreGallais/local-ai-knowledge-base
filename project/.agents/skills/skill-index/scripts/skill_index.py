"""Builds .agents/skills/SKILLS_INDEX.md from the headers of the finished skills, and searches it.

The same commands and output as skill-index.ts, for a machine without Node. Python 3.9 or later,
standard library only. Run from the root of the project:
    python3 .agents/skills/skill-index/scripts/skill_index.py build
    python3 .agents/skills/skill-index/scripts/skill_index.py check
    python3 .agents/skills/skill-index/scripts/skill_index.py search <word> [<word>...]
"""

import os
import re
import sys

MAX_RESULTS = 5
HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SKILLS = os.path.normpath(os.path.join(HERE, "..", ".."))
KEY_LINE = re.compile(r"^(\s*)([A-Za-z_][\w-]*):(?:\s+(.*))?$")


def unquote(value):
    trimmed = value.strip()
    if re.match(r"^([\"']).*\1$", trimmed):
        return trimmed[1:-1]
    return trimmed


def fields(text):
    lines = text.replace("\r\n", "\n").split("\n")
    result = {}
    end = -1
    if lines and lines[0] == "---":
        try:
            end = lines.index("---", 1)
        except ValueError:
            end = -1
    parent = ""
    for line in lines[1 : max(end, 1)]:
        match = KEY_LINE.match(line)
        if match is None:
            continue
        nested = match.group(1) != ""
        value = match.group(3) or ""
        key = parent + "." + match.group(2) if nested else match.group(2)
        result[key] = unquote(value)
        if not nested:
            parent = match.group(2) if value.strip() == "" else ""
    return result


def entries(skills):
    result = []
    for name in sorted(os.listdir(skills)):
        path = os.path.join(skills, name, "SKILL.md")
        if name.startswith("_") or not os.path.isdir(os.path.join(skills, name)) or not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as handle:
            header = fields(handle.read())
        identifier = header.get("metadata.id", "")
        tags = [tag for tag in (identifier.split("-")[0], header.get("metadata.nature", "")) if tag != ""]
        result.append({
            "name": header.get("name", ""),
            "load": header.get("metadata.load", ""),
            "tags": ", ".join(tags),
            "description": header.get("description", ""),
        })
    return sorted(result, key=lambda entry: entry["name"])


def cell(text):
    return text.replace("|", "\\|")


def render(items):
    lines = [
        "# Skills index",
        "",
        "Generated by `node .agents/skills/skill-index/scripts/skill-index.ts build`. Do not edit by hand.",
        f"{len(items)} skills. Load at most 3 for one task with the `skill` tool.",
        "",
        "| Skill | Load | Tags | Description |",
        "| --- | --- | --- | --- |",
    ]
    rows = [f"| `{entry['name']}` | {entry['load']} | {cell(entry['tags'])} | {cell(entry['description'])} |" for entry in items]
    return "\n".join([
        *lines,
        *rows,
        "",
    ])


def words(text):
    return [word for word in re.split(r"[^a-z0-9]+", text.lower()) if len(word) > 1]


def search(items, query):
    wanted = [word for item in query for word in words(item)]
    scored = []
    for entry in items:
        name = words(entry["name"])
        rest = words(entry["tags"] + " " + entry["description"])
        score = sum((3 if word in name else 0) + (1 if word in rest else 0) for word in wanted)
        if score > 0:
            scored.append((-score, entry["name"], entry))
    scored.sort(key=lambda item: (item[0], item[1]))
    return [item[2] for item in scored[:MAX_RESULTS]]


def main():
    args = sys.argv[1:]
    command = args[0] if args else ""
    skills = os.environ.get("SKILLS_DIR", DEFAULT_SKILLS)
    path = os.path.join(skills, "SKILLS_INDEX.md")
    text = render(entries(skills))
    if command == "build":
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        print("Wrote " + path + ".")
        return 0
    if command == "check":
        fresh = False
        if os.path.exists(path):
            with open(path, encoding="utf-8", newline="") as handle:
                fresh = handle.read() == text
        print("SKILLS_INDEX.md is up to date." if fresh else "SKILLS_INDEX.md is stale: run the build command.")
        return 0 if fresh else 1
    if command == "search" and len(args) > 1:
        found = search(entries(skills), args[1:])
        for entry in found:
            print(f"{entry['name']} ({entry['load']}): {entry['description']}")
        print(f"{len(found)} results.")
        return 0
    print("Usage: python3 skill_index.py build | check | search <word> [<word>...]")
    return 2


if __name__ == "__main__":
    sys.exit(main())
