export interface RawCard {
  english: string;
  document: string;
  properties: string;
  states: string;
  subtypes: string;
}

export interface Property {
  name: string;
  type: string;
}

export interface TypeFile {
  name: string;
  text: string;
}

export interface Generation {
  files: TypeFile[];
  warnings: string[];
}

