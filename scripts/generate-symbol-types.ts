// Generates the TypeScript types of the symbol properties from the catalog cards (docs/synoptics):
// one interface per card, one file per card, and the shared sets and enums.
//
// node scripts/generate-symbol-types.ts            formatted, in global/kit/symbols
// node scripts/generate-symbol-types.ts --out <dir>  raw, in <dir>
//
// The formatted mode runs the format pass in the TypeScript library sample: it needs the sample
// packages (npm install --prefix samples). The hand-written *.spec.ts files of the kit stay.
