function words(text: string): string[] {
  return text
    .split(/[^A-Za-z0-9]+/)
    .filter((word) => word !== '');
}

// A type name cannot start with a digit: the leading numbers go to the end, "4 to 20 mA current loop"
// gives "MaCurrentLoop4To20".
export function pascalCase(text: string): string {
  const parts = words(text).map((word) => `${word.charAt(0).toUpperCase()}${word.slice(1).toLowerCase()}`);
  const lastNumber = parts.findLastIndex((part) => /^\d/.test(part));
  const lead = /^\d/.test(parts[0] ?? '') ? parts.slice(0, lastNumber + 1) : [];

  return [
    ...parts.slice(lead.length),
    ...lead,
  ].join('');
}

function kebabOfPascal(name: string): string {
  return name
    .replaceAll(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase();
}

export function kebabCase(text: string): string {
  return kebabOfPascal(pascalCase(text));
}

// The name of the interface of a shared set: "panelDevice" gives "PanelDeviceSet".
function setName(set: string): string {
  return `${set.charAt(0).toUpperCase()}${set.slice(1)}Set`;
}

function backticked(text: string): string[] {
  return [...text.matchAll(/`(\w+)`/g)].map((match) => match[1] ?? '');
}

function union(values: readonly string[]): string {
  return values
    .map((value) => `'${value}'`)
    .join(' | ');
}

// The values of an enum property named in the subtypes line: "`pumpType` `a` or `b`; ...".
function subtypeValues(name: string, subtypes: string): string[] {
  for (const segment of subtypes.split(';')) {
    const values = backticked(segment);

    if (values[0] === name && values.length > 2) {
      return values.slice(1);
    }
  }
  return [];
}

function enumType(name: string, descriptor: string, card: RawCard | undefined): string | undefined {
  const head = descriptor.split(';')[0] ?? '';
  const values = backticked(head);

  if (values.length > 1 && !/\bof\b/.test(head)) {
    return union(values);
  }
  if (card !== undefined && /\babove\b/.test(head) && backticked(card.states).length > 1) {
    return union(backticked(card.states));
  }
  const fromSubtypes = card === undefined ? [] : subtypeValues(name, card.subtypes);

  return fromSubtypes.length > 0 ? union(fromSubtypes) : undefined;
}

export function propertyType(name: string, descriptor: string, card?: RawCard): string | undefined {
  const head = descriptor.trim();
  const known = ENUM_OF_PROPERTY[name];

  if (known !== undefined) {
    return known;
  }
  if (name === 'compartments' || name === 'tanks') {
    return TWIN;
  }
  if (head.startsWith('number[]')) {
    return 'readonly number[]';
  }
  if (head.startsWith('string[]')) {
    return 'readonly string[]';
  }
  if (/^(?:number|integer)\b/.test(head)) {
    return 'number';
  }
  if (head.startsWith('boolean')) {
    return 'boolean';
  }
  if (head.startsWith('string')) {
    return 'string';
  }
  if (head.startsWith('object')) {
    return MEASUREMENT;
  }
  if (/^(?:enums?\b|`)/.test(head)) {
    return enumType(name, head, card) ?? 'string';
  }
  return undefined;
}

export function readProperties(text: string, card?: RawCard): {
  properties: Property[];
  unknown: string[];
} {
  const properties: Property[] = [];
  const unknown: string[] = [];

  for (const match of text.matchAll(GROUP)) {
    const names = backticked(match[1] ?? '');
    const type = propertyType(names[0] ?? '', match[2] ?? '', card);

    if (type === undefined) {
      unknown.push(match[0]);
    } else {
      properties.push(...names.map((name) => ({
        name,
        type,
      })));
    }
  }
  return {
    properties,
    unknown,
  };
}

// The shared sets a segment names: "set `a`", "sets `a` and `b`", "set `a` or `b`" (the first one),
// "set `a` without `k`", "`k`, `l` of the set `a`".
function setParents(segment: string): string[] {
  const set = /\bsets? ((?:`\w+`(?:, | and | or )?)+)(?: without ((?:`\w+`(?:, | and )?)+))?/.exec(segment);
  const pick = /^\s*((?:`\w+`(?:, )?)+) of the set `(\w+)`/.exec(segment);

  if (pick !== null) {
    return [`Pick<${setName(pick[2] ?? '')}, ${union(backticked(pick[1] ?? ''))}>`];
  }
  if (set === null) {
    return [];
  }
  const names = backticked(set[1] ?? '');
  const sets = (set[1] ?? '').includes(' or ') ? names.slice(0, 1) : names;
  const without = backticked(set[2] ?? '');

  return sets.map((name) => (without.length > 0 ? `Omit<${setName(name)}, ${union(without)}>` : setName(name)));
}

// The cards a segment names: "those of the <card> and the <card>", "properties of the <card>".
function cardParents(segment: string, own: string, cardNames: ReadonlyMap<string, string>): string[] {
  const those = /\b(?:those|properties) of the ([^;.`(]+)/.exec(segment);

  return (those?.[1] ?? '')
    .split(/,| and the | and /)
    .map((part) => cardNames.get(part
      .trim()
      .replace(/^the /, '')))
    .filter((parent): parent is string => parent !== undefined && parent !== own)
    .map((parent) => `${parent}Properties`);
}

function parents(card: RawCard, cardNames: ReadonlyMap<string, string>): string[] {
  const own = pascalCase(card.english);

  return [
    ...new Set(card.properties
      .split(';')
      .flatMap((segment) => [
        ...setParents(segment),
        ...cardParents(segment, own, cardNames),
      ])),
  ];
}

function addField(card: RawCard, line: string): void {
  card.properties = line.startsWith('- Properties:') ? line.slice(13) : card.properties;
  card.states = line.startsWith('- States:') ? line.slice(9) : card.states;
  card.subtypes = line.startsWith('- Subtypes:') ? line.slice(11) : card.subtypes;
}

// The cards of a document; a heading that is not a card ends the card before it.
export function readRawCards(text: string, document: string): RawCard[] {
  const cards: RawCard[] = [];
  let isInFence = false;

  for (const line of splitLines(text)) {
    const card = cards.at(-1);

    if (line.startsWith('```')) {
      isInFence = !isInFence;
    } else if (!isInFence && /^#{2,3} /.test(line)) {
      cards.push({
        english: CARD_HEADING.exec(line)?.[1] ?? '',
        document,
        properties: '',
        states: '',
        subtypes: '',
      });
    } else if (card !== undefined && !isInFence) {
      addField(card, line);
    }
  }
  return cards.filter((item) => item.english !== '');
}

// The rows "| `set` (...) | properties |" of the shared set tables.
export function readSets(text: string): Map<string, Property[]> {
  const sets = new Map<string, Property[]>();

  for (const line of splitLines(text).filter((item) => item.startsWith('| `'))) {
    const cells = line.split('|');
    const name = backticked(cells[1] ?? '')[0];

    if (name !== undefined) {
      sets.set(name, readProperties(cells.slice(2).join('|')).properties);
    }
  }
  return sets;
}

function member(property: Property): string {
  return `  readonly ${property.name}: ${property.type};`;
}

function sharedFile(sets: ReadonlyMap<string, Property[]>): string {
  const enums = Object
    .entries(ENUMS)
    .map(([
      name,
      values,
    ]) => `export type ${name} = ${union(values)};\n`);
  const interfaces = [...sets].map(([
    name,
    properties,
  ]) => `/** The shared set "${name}" of docs/synoptics. */\nexport interface ${setName(name)} {\n${properties.map((property) => member(property)).join('\n')}\n}\n`);

  return [
    GENERATED_NOTE,
    ...enums,
    `export interface ${MEASUREMENT} {\n  readonly value: number;\n  readonly unit: string;\n}\n`,
    'export interface TankCompartment extends TankSet {\n  readonly compartmentId: \'a\' | \'b\';\n}\n',
    ...interfaces,
  ].join('\n');
}

function importedNames(type: string, shared: ReadonlySet<string>): string[] {
  return (type.match(/\b[A-Z]\w+/g) ?? []).filter((name) => shared.has(name));
}

function cardFile(card: RawCard, own: readonly Property[], extend: readonly string[], shared: ReadonlySet<string>): string {
  const name = `${pascalCase(card.english)}Properties`;
  const fromShared = new Set([
    ...own.flatMap((property) => importedNames(property.type, shared)),
    ...extend.flatMap((parent) => importedNames(parent, shared)),
  ]);
  const fromCards = extend
    .filter((parent) => !shared.has(parent) && /^[A-Z]\w+Properties$/.test(parent))
    .map((parent) => `import type { ${parent} } from './${kebabOfPascal(parent.replace(/Properties$/, ''))}.ts';\n`);
  const imports = [
    ...fromShared.size > 0 ? [`import type { ${[...fromShared].sort().join(', ')} } from './${SHARED_FILE}.ts';\n`] : [],
    ...fromCards,
  ];
  const heritage = extend.length > 0 ? ` extends ${extend.join(', ')}` : '';
  const doc = `/** The properties of the card "${card.english}" of docs/synoptics/${card.document}. */\n`;
  const body = own.length > 0 ? `{\n${own.map((property) => member(property)).join('\n')}\n}` : '{}';

  if (own.length === 0 && extend.length === 1) {
    return [
      GENERATED_NOTE,
      ...imports,
      `${doc}export type ${name} = ${extend[0] ?? ''};\n`,
    ].join('\n');
  }
  return [
    GENERATED_NOTE,
    ...imports,
    `${doc}export interface ${name}${heritage} ${body}\n`,
  ].join('\n');
}

function uniqueProperties(properties: readonly Property[], name: string, warnings: string[]): Property[] {
  const seen = new Map<string, string>();

  for (const property of properties) {
    const before = seen.get(property.name);

    if (before !== undefined && before !== property.type) {
      warnings.push(`${name}: "${property.name}" has two types, ${before} and ${property.type}`);
    }
    seen.set(property.name, before ?? property.type);
  }
  return [...seen].map(([
    propertyName,
    type,
  ]) => ({
    name: propertyName,
    type,
  }));
}

function sharedNames(sets: ReadonlyMap<string, Property[]>): Set<string> {
  return new Set([
    ...Object.keys(ENUMS),
    ...[...sets.keys()].map((name) => setName(name)),
    MEASUREMENT,
    'TankCompartment',
  ]);
}

export function generateSymbolTypes(documents: readonly TypeFile[]): Generation {
  const warnings: string[] = [];
  const sets = new Map(documents
    .filter((item) => SET_TABLES.includes(item.name))
    .flatMap((item) => [...readSets(item.text)]));
  const shared = sharedNames(sets);
  const cards = documents
    .filter((item) => item.name.startsWith('catalog-'))
    .flatMap((item) => readRawCards(item.text, item.name));
  const cardNames = new Map(cards.map((card) => [
    card.english.toLowerCase(),
    pascalCase(card.english),
  ]));
  const files: TypeFile[] = [
    {
      name: `${SHARED_FILE}.ts`,
      text: sharedFile(sets),
    },
  ];

  for (const card of cards) {
    const read = readProperties(card.properties, card);
    const extend = parents(card, cardNames);

    warnings.push(...read.unknown.map((group) => `${card.english}: no type for ${group}`));
    if (read.properties.length === 0 && extend.length === 0) {
      warnings.push(`${card.english}: no property, no file`);
    } else {
      files.push({
        name: `${kebabCase(card.english)}.ts`,
        text: cardFile(card, uniqueProperties(read.properties, card.english, warnings), extend, shared),
      });
    }
  }
  return {
    files,
    warnings,
  };
}

export function readSynoptics(folder: string = SYNOPTICS): TypeFile[] {
  return readdirSync(folder)
    .filter((name) => name.endsWith('.md'))
    .sort()
    .map((name) => ({
      name,
      text: readFileSync(join(folder, name), 'utf8'),
    }));
}

export function writeTypeFiles(files: readonly TypeFile[], folder: string): void {
  mkdirSync(folder, { recursive: true });
  for (const file of files) {
    writeFileSync(join(folder, file.name), file.text);
  }
}

// Writes the raw types in the TypeScript library sample, runs the format pass there, and returns the
// formatted files without the copyright header of the sample.
export function formatTypeFiles(files: readonly TypeFile[]): TypeFile[] {
  const work = join(SAMPLE, 'src', 'zz-symbols-generated');

  rmSync(work, {
    recursive: true,
    force: true,
  });
  writeTypeFiles(files, work);
  try {
    const format = spawnSync(
      process.execPath,
      [
        join(ROOT, 'global', 'tools', 'format-file.ts'),
        '--all',
      ],
      {
        cwd: SAMPLE,
        encoding: 'utf8',
      },
    );

    if (format.status !== 0) {
      throw new Error(`the format pass failed: ${format.stdout}${format.stderr}`);
    }
    return files.map((file) => ({
      name: file.name,
      text: readFileSync(join(work, file.name), 'utf8').replace(SAMPLE_HEADER, ''),
    }));
  } finally {
    rmSync(work, {
      recursive: true,
      force: true,
    });
  }
}

function main(): void {
  const args = process.argv.slice(2);
  const outIndex = args.indexOf('--out');
  const generation = generateSymbolTypes(readSynoptics());

  for (const warning of generation.warnings) {
    console.log(`warning: ${warning}`);
  }
  if (outIndex >= 0) {
    writeTypeFiles(generation.files, resolve(args[outIndex + 1] ?? ''));
    console.log(`${generation.files.length} raw file(s) written.`);
    return;
  }
  for (const name of readdirSync(KIT_SYMBOLS).filter((item) => !item.endsWith('.spec.ts'))) {
    rmSync(join(KIT_SYMBOLS, name));
  }
  writeTypeFiles(formatTypeFiles(generation.files), KIT_SYMBOLS);
  console.log(`${generation.files.length} formatted file(s) written in global/kit/symbols.`);
}

if (process.argv[1] !== undefined && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  main();
}
